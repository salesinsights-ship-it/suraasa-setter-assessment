import React, { useCallback, useEffect, useState } from 'react';
import { rpc } from '../api.js';
import { Btn, Loading, go } from '../ui.jsx';
import ReportView from './ReportView.jsx';

/** What a candidate sees after a call. The server decides how much feedback is included. */
export default function Result({ sessionId }) {
  const [data, setData] = useState(null);
  const [error, setError] = useState('');
  const [busy, setBusy] = useState(false);
  const load = useCallback(() => rpc('getSession', { session_id: sessionId }).then(setData).catch((e) => setError(e.message)), [sessionId]);
  useEffect(() => { load(); }, [load]);

  async function retry() {
    setBusy(true); setError('');
    try {
      const r = await rpc('score', { session_id: sessionId });
      if (r.pending) setError(`The AI is busy right now. Try again in about ${r.retry_after} seconds.`);
      await load();
    } catch (e) { setError(e.message); } finally { setBusy(false); }
  }

  if (!data && !error) return <Loading />;
  const s = data?.session;
  return (
    <div className="page">
      <p className="no-print"><a href="#/">Back to your dashboard</a></p>
      <div className="head mt"><h1>Your call result</h1>{data?.report && <Btn onClick={() => window.print()}>Download as PDF</Btn>}</div>
      {error && <div className="note bad" style={{ marginBottom: 16 }}>{error}</div>}
      {s && s.voided && <div className="note">Your recruiter has set this call aside, so it does not count. You may be given another attempt.</div>}
      {s && !s.voided && s.status === 'ended' && (
        <div className="card col"><h2>Your call is saved and waiting to be assessed</h2><p>Scoring did not finish, usually because the AI service was busy. Your call is safe.</p><div><Btn kind="primary" busy={busy} onClick={retry}>Assess my call now</Btn></div></div>
      )}
      {s && !s.voided && s.status === 'incomplete' && <div className="note warn">This call was too short to be assessed. It has not used an attempt.</div>}
      {s && !s.voided && s.status === 'scored' && !data.report && (
        <div className="card col" data-testid="submitted"><h2>Thank you. Your call has been submitted.</h2><p>Your recruiter will review it and get back to you. Feedback for this assessment is shared by the recruitment team.</p><div><Btn onClick={() => go('/')}>Back to your dashboard</Btn></div></div>
      )}
      {data?.report && (
        <>
          <ReportView report={data.report} staff={false} />
          <p className="small muted mt">{data.report.training ? 'This feedback is generated by AI from your practice call, and your trainer can see it too. Use it to plan your next call.' : 'This feedback is generated by AI from your call and is reviewed by a recruiter. It is one input into the hiring decision, not the decision itself.'}</p>
        </>
      )}
    </div>
  );
}
